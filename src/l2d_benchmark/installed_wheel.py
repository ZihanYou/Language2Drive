"""Reuse the installed distribution when provisioning isolated runtime environments."""
import base64
import csv
import hashlib
from importlib.metadata import distribution
import io
from pathlib import Path, PurePosixPath
import zipfile


def cached_wheel(root, dry_run=False):
    dist = distribution('language2drive')
    destination = Path(root) / '.l2d/wheels' / ('language2drive-' + dist.version + '-py3-none-any.whl')
    if dry_run:
        return destination
    payload, records = {}, []
    for item in dist.files or []:
        name = str(item)
        # Generated launchers live outside site-packages and are regenerated by pip.
        if '..' in PurePosixPath(name).parts or item.suffix == '.pyc' or name.endswith('.dist-info/RECORD'):
            continue
        source = Path(dist.locate_file(item))
        if not source.is_file():
            raise FileNotFoundError('Installed distribution is incomplete: ' + name)
        data = source.read_bytes()
        if item.hash and item.hash.mode == 'sha256':
            digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip('=')
            if digest != item.hash.value:
                raise ValueError('Installed package was modified: ' + name + '; provide --package explicitly')
        payload[name] = data
    if not any(name.endswith('.dist-info/WHEEL') for name in payload):
        raise ValueError('Cannot reuse an editable distribution; supply --package /path/to/checkout')
    for name, data in payload.items():
        digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip('=')
        records.append([name, 'sha256=' + digest, len(data)])
    record = next(n.rsplit('/', 1)[0] + '/RECORD' for n in payload if n.endswith('.dist-info/WHEEL'))
    records.append([record, '', ''])
    stream = io.StringIO(); csv.writer(stream, lineterminator='\n').writerows(records)
    payload[record] = stream.getvalue().encode()
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix('.tmp')
    with zipfile.ZipFile(temporary, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in payload.items():
            archive.writestr(name, data)
    temporary.replace(destination)
    return destination
