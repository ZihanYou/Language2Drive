"""Score one declared evaluation scope using its saved execution authority."""
from __future__ import annotations
import json
from pathlib import Path
from .io import atomic_json, sha256_file, stable_hash
from .metrics import aggregate, _execution_bundle_is_full, _strict_json_object
from .runner import _validate_plan_sha256
from .scoring import _targets_for_suite, score_one, _fdq_summary, _safety_summary


def stamp_scope(plan, args, ledger, root):
    """Bind the complete requested scope, including jobs skipped on resume."""
    runs = _strict_json_object(ledger)['runs']
    seeds = getattr(args, 'seeds', [1])
    split = getattr(args, 'split', 'dev' if args.command in {'run-safety', 'run-baseline'} else None)
    track = plan['track']
    route_ids = getattr(args, 'route_entry_ids', None)
    expected = [r for r in runs if r['seed'] in seeds
                and (split is None or r.get('split') == split)
                and (r.get('track', track) == track)
                and (not route_ids or r.get('route_entry_id') in route_ids)]
    plan['evaluation_scope'] = {
        'schema_version': 'language2drive.release_scope.v1',
        'ledger': str(ledger.relative_to(root)), 'ledger_sha256': sha256_file(ledger),
        'split': split, 'seeds': seeds, 'tier': getattr(args, 'tier', None),
        'run_ids': [r['run_id'] for r in expected],
    }
    plan['plan_sha256'] = stable_hash({k: v for k, v in plan.items() if k != 'plan_sha256'})


def score_plan(root: Path, plan_path: Path, results: Path, output: Path):
    plan = _strict_json_object(plan_path)
    _validate_plan_sha256(plan)
    bundle = plan['input_hashes']
    workload = plan['workload']
    if not _execution_bundle_is_full(bundle, workload=workload):
        raise ValueError('The saved plan has no complete execution authority.')
    scope = plan.get('evaluation_scope')
    if not isinstance(scope, dict) or scope.get('schema_version') != 'language2drive.release_scope.v1':
        raise ValueError('Use a plan generated by this release to score its complete scope.')
    ledger = (root / scope['ledger']).resolve()
    if not ledger.is_relative_to(root.resolve()) or sha256_file(ledger) != scope['ledger_sha256']:
        raise ValueError('The evaluation ledger differs from the saved plan.')
    ledger_runs = _strict_json_object(ledger)['runs']
    by_id = {r['run_id']: r for r in ledger_runs}
    ids = scope['run_ids']
    if len(set(ids)) != len(ids) or any(x not in by_id for x in ids) or not ids:
        raise ValueError('The evaluation scope contains invalid or duplicate run identities.')
    runs = [by_id[x] for x in ids]
    if workload == 'fdq':
        result = _fdq_summary(ledger, results, expected_input_hashes=bundle,
                              materialized_runs=runs, expected_count=len(runs))
    else:
        authority = plan['execution_authority']
        sidecar_path = Path(authority['sidecar'])
        if sha256_file(sidecar_path) != bundle['private_sidecar_sha256']:
            raise ValueError('The private sidecar differs from the executed plan.')
        sidecar = _strict_json_object(sidecar_path)
        targets = _targets_for_suite(root, sidecar)
        overrides = {}
        for run in runs:
            if not (results / run['run_id']).is_dir():
                continue
            value = score_one(run, project_root=root, results_dir=results,
                              sidecar=sidecar, target_index=targets, write_result=False)
            if value is not None:
                overrides[run['run_id']] = value
        if workload == 'safety_priority':
            result = _safety_summary(ledger, results, expected_input_hashes=bundle,
                                    result_overrides=overrides, materialized_runs=runs)
        else:
            result = aggregate(ledger, results, expected_input_hashes=bundle,
                               result_overrides=overrides, materialized_runs=runs)
            groups = {}
            for row in result['rows']:
                key = (row['pcu_id'], row['paraphrase'], row['seed'])
                groups.setdefault(key, []).append(row)
            semantic = {k: len(v) == 2 and len({r['arm_id'] for r in v}) == 2
                        and all(r.get('result_valid') and r.get('semantic_success') for r in v)
                        for k, v in groups.items()}
            result['Sem-CFPS'] = {
                layer: (sum(v for k, v in semantic.items() if k[0].startswith(layer)) /
                        sum(1 for k in semantic if k[0].startswith(layer)))
                if any(k[0].startswith(layer) for k in semantic) else None
                for layer in 'ABCD'}
    payload = {'schema_version': 'language2drive.release_score.v1',
               'model': plan['agent'], 'track': plan['track'], 'workload': workload,
               'scope': scope, 'plan_sha256': plan['plan_sha256'],
               'plan_file_sha256': sha256_file(plan_path), 'metrics': result}
    atomic_json(output, payload)
    return payload
